export function iconCells(name: IconName) {
  const cells: Array<{ x: number; y: number; c: string }> = [];
  ICONS[name].forEach((row, y) => [...row].forEach((c, x) => c !== '.' && x < 9 && cells.push({ x, y, c })));
  return cells;
}
