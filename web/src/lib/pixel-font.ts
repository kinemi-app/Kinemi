export const ROWS = 7;

export interface Cell {
  x: number;
  y: number;
  /** index of the glyph within the text, useful for staggering */
  g: number;
}

export interface PixelLayout {
  cells: Cell[];
  width: number;
  height: number;
}

export interface LayoutOptions {
  /** empty columns between glyphs */
  gap?: number;
  /** empty rows between lines */
  lineGap?: number;
  align?: 'left' | 'center' | 'right';
}

export function layout(text: string, opts: LayoutOptions = {}): PixelLayout {
  const { gap = 1, lineGap = 2, align = 'left' } = opts;
  const lines = text.toUpperCase().split('\n');
  const rendered = lines.map((line) => {
    const cells: Cell[] = [];
    let x = 0;
    [...line].forEach((ch, i) => {
      const glyph = G[ch] ?? G['?'];
      glyph.forEach((row, y) => {
        [...row].forEach((c, dx) => {
          if (c === '#') cells.push({ x: x + dx, y, g: i });
        });
      });
      x += glyph[0].length + (i < line.length - 1 ? gap : 0);
    });
    return { cells, width: x };
  });
  const width = Math.max(...rendered.map((l) => l.width));
  const cells: Cell[] = [];
  let glyphOffset = 0;
  rendered.forEach((line, li) => {
    const shift = align === 'center' ? Math.floor((width - line.width) / 2) : align === 'right' ? width - line.width : 0;
    const y0 = li * (ROWS + lineGap);
    line.cells.forEach((c) => cells.push({ x: c.x + shift, y: c.y + y0, g: c.g + glyphOffset }));
    glyphOffset += lines[li].length;
  });
  return { cells, width, height: lines.length * ROWS + (lines.length - 1) * lineGap };
}

/** Merge each row's neighbouring cells into runs: one compact path for static text. */
export function toPath(cells: Cell[]): string {
  const rows = new Map<number, number[]>();
  for (const c of cells) {
    if (!rows.has(c.y)) rows.set(c.y, []);
    rows.get(c.y)!.push(c.x);
  }
  let d = '';
  for (const [y, xs] of rows) {
    xs.sort((a, b) => a - b);
    let start = xs[0];
    let prev = xs[0];
    for (let i = 1; i <= xs.length; i++) {
      const x = xs[i];
      if (x === prev + 1) {
        prev = x;
        continue;
      }
      d += `M${start} ${y}h${prev - start + 1}v1h-${prev - start + 1}z`;
      start = prev = x;
    }
  }
  return d;
}
